// Refreshes frontend/src/content/upstreamSnapshot.ts from GrsAI's public model list with
// the same validation as the hourly backend sync (ADR-008). The file is left untouched when
// nothing changed, so its date marks the last real change. A new upstream model appears on
// the public site only after it gets an editorial row in catalogue.ts; this script lists them.
// Usage: npm run catalogue:sync
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fetchUpstreamCatalog } from "../src/upstream-catalog.ts";

type UpstreamPrice = { closed: boolean; input?: string | null; output?: string | null; cache?: string | null; request?: string | null };

const target = new URL("../frontend/src/content/upstreamSnapshot.ts", import.meta.url);
const editorial = readFileSync(new URL("../frontend/src/content/catalogue.ts", import.meta.url), "utf8");
const credits = (value: number | null) => value === null ? null : String(value);

const catalog = await fetchUpstreamCatalog();
const models: Record<string, UpstreamPrice> = {};
for (const model of [...catalog.models].sort((a, b) => a.id.localeCompare(b.id))) {
  models[model.id] = model.capability === "text"
    ? { closed: model.closed, input: credits(model.input_credits), output: credits(model.output_credits), cache: credits(model.cache_credits) }
    : { closed: model.closed, request: credits(model.unit_credits) };
}

const render = (checkedOn: string) => `// Generated by \`npm run catalogue:sync\` from GrsAI's public model list. Do not edit by hand.
// Text: credits per 1M tokens. Image: credits per request. closed: GrsAI lists the model as unavailable.
export type UpstreamPrice = { closed: boolean; input?: string | null; output?: string | null; cache?: string | null; request?: string | null };

export const upstreamSnapshot: { checkedOn: string; source: string; models: Record<string, UpstreamPrice> } = ${JSON.stringify({
  checkedOn, source: "https://grsai.com/dashboard/models", models }, null, 2)};
`;

const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
const previousDate = /"checkedOn": "(\d{4}-\d{2}-\d{2})"/.exec(current)?.[1];
if (previousDate && render(previousDate) === current) {
  console.log(`Unchanged since ${previousDate}.`);
} else {
  const previous: Record<string, UpstreamPrice> = current
    ? (await import(target.href) as { upstreamSnapshot: { models: Record<string, UpstreamPrice> } }).upstreamSnapshot.models : {};
  writeFileSync(target, render(new Date().toISOString().slice(0, 10)));
  for (const id of new Set([...Object.keys(previous), ...Object.keys(models)])) {
    const before = previous[id], after = models[id];
    if (!before) console.log(`added    ${id}`);
    else if (!after) console.log(`removed  ${id}`);
    else if (JSON.stringify(before) !== JSON.stringify(after)) console.log(`changed  ${id}: ${JSON.stringify(before)} -> ${JSON.stringify(after)}`);
  }
}
for (const id of Object.keys(models)) {
  if (!editorial.includes(`"${id}"`)) console.log(`not published: ${id} has no editorial row in frontend/src/content/catalogue.ts`);
}
